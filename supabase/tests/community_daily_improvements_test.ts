import { PGlite } from 'npm:@electric-sql/pglite@0.3';
import assert from 'node:assert/strict';

Deno.test('handles, member publications, moderation and retention diagnostics respect permissions', async () => {
 const db=new PGlite();
 const leader='ad300000-0000-4000-8000-000000000001', member='ad300000-0000-4000-8000-000000000002', viewer='ad300000-0000-4000-8000-000000000003';
 try {
 await db.exec(`create role anon;create role authenticated;create schema auth;
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to anon,authenticated;
 create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}',created_at timestamptz default now());
 create table public.profiles(id uuid primary key,display_name text,avatar_url text,is_public boolean default true,role text default 'member');
 create table public.community_blocks(blocker_id uuid,blocked_id uuid);
 create function public.is_admin() returns boolean language sql stable security definer as $$select auth.uid()='${leader}'::uuid$$;
 create function public.admin_search_members(text,integer) returns text language sql as $$select ''::text$$;
 create table public.community_posts(id uuid primary key,user_id uuid references auth.users(id),content text,created_at timestamptz default now());
 create table public.community_comments(id uuid primary key,user_id uuid references auth.users(id),content text);
 create table public.community_photo_cleanup(post_id uuid);
 create view public.community_feed as select p.* from public.community_posts p where not exists(select 1 from public.community_blocks b where (b.blocker_id=auth.uid() and b.blocked_id=p.user_id) or (b.blocker_id=p.user_id and b.blocked_id=auth.uid()));
 grant insert on public.community_posts,public.community_comments to authenticated;
 insert into auth.users(id,email,email_confirmed_at) values('${leader}','amaralaragao31@gmail.com',now()),('${member}','member@example.invalid',now()),('${viewer}','viewer@example.invalid',now());
 insert into public.profiles(id,display_name,role) values('${leader}','Leader','admin'),('${member}','Same Name','member'),('${viewer}','Same Name','member');
 insert into public.community_posts values('${member}','${member}','hello',now()-interval '8 days');
 insert into public.community_posts values('${leader}','${leader}','leader',now()-interval '8 days');`);
 for(const file of ['20261103000100_member_handles.sql','20261103000200_member_publications.sql','20261103000300_community_moderation_health.sql']) await db.exec(await Deno.readTextFile(new URL('../migrations/'+file,import.meta.url)));
 const asUser=async(id:string,role='authenticated')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role '+role);};
 await asUser(member);
 assert.equal((await db.query<any>('select public.set_member_handle($1) h',[' Arthur_Morgan '])).rows[0].h,'arthur_morgan');
 await assert.rejects(db.query('select public.set_member_handle($1)',['bad-name']),/Use de 3/);
 await assert.rejects(db.query('select * from public.member_handles'),/permission denied/);
 await assert.rejects(db.query('select * from public.admin_search_members()'),/Admin access/);
 await assert.rejects(db.query('select public.admin_community_health()'),/Admin access/);
 await assert.rejects(db.query('select public.admin_restrict_community_member($1,7)',[leader]),/Admin access/);
 await asUser(viewer);
 await assert.rejects(db.query('select public.set_member_handle($1)',['ARTHUR_MORGAN']),/já está em uso/);
 assert.equal((await db.query<any>('select public.member_handle($1) h',[member])).rows[0].h,'arthur_morgan');
 assert.equal((await db.query('select * from public.member_publications($1)',[member])).rows.length,1);
 await db.exec('reset role');await db.query('update public.profiles set is_public=false where id=$1',[member]);
 await asUser(viewer);
 assert.equal((await db.query<any>('select public.member_handle($1) h',[member])).rows[0].h,null);
 assert.equal((await db.query('select * from public.member_publications($1)',[member])).rows.length,0);
 await asUser(member);
 assert.equal((await db.query('select * from public.member_publications($1)',[member])).rows.length,1);
 await db.exec('reset role');await db.query('update public.profiles set is_public=true where id=$1',[member]);
 await db.query('insert into public.community_blocks values($1,$2)',[member,viewer]);
 await asUser(viewer);
 assert.equal((await db.query<any>('select public.member_handle($1) h',[member])).rows[0].h,null);
 assert.equal((await db.query('select * from public.member_publications($1)',[member])).rows.length,0);
 await asUser(leader);
 const found=(await db.query<any>('select * from public.admin_search_members($1)', ['@arthur_morgan'])).rows;
 assert.equal(found.length,1);assert.equal(found[0].user_id,member);assert.equal(found[0].handle,'arthur_morgan');
 await db.query('select public.admin_restrict_community_member($1,7)',[member]);
 await assert.rejects(db.query('select public.admin_restrict_community_member($1,7)',[leader]),/não pode ser restringido/);
 await asUser(member);
 await assert.rejects(db.query('insert into public.community_posts(id,user_id,content) values($1,$2,$3)',[viewer,member,'denied']),/temporariamente restrita/);
 await assert.rejects(db.query('insert into public.community_comments(id,user_id,content) values($1,$2,$3)',[viewer,member,'denied']),/temporariamente restrita/);
 await asUser(leader);
 let health=(await db.query<any>('select public.admin_community_health() h')).rows[0].h;
 assert.equal(health.expired_posts,1);assert.equal(health.scheduled,false);assert.equal(health.restrictions.length,1);
 await db.query('select public.admin_clear_community_restriction($1)',[member]);
 await asUser(member);
 await db.query('insert into public.community_comments(id,user_id,content) values($1,$2,$3)',[viewer,member,'allowed']);
 await db.exec('reset role');
 await db.exec(`create schema cron;create table cron.job(jobid int,jobname text,active boolean,schedule text);create table cron.job_run_details(jobid int,runid int,status text,end_time timestamptz);
 insert into cron.job values(1,'pbh-expire-community-member-posts',true,'*/5 * * * *');insert into cron.job_run_details values(1,1,'succeeded',now());`);
 await asUser(leader);
 health=(await db.query<any>('select public.admin_community_health() h')).rows[0].h;
 assert.equal(health.scheduled,true);assert.equal(health.last_status,'succeeded');assert.equal(health.restrictions.length,0);
 } finally {await db.close();}
});
