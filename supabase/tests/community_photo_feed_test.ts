import { PGlite } from 'npm:@electric-sql/pglite@0.3';
import assert from 'node:assert/strict';

Deno.test('community photos enforce ownership, publication visibility and cleanup', async () => {
  const db = new PGlite();
  const owner='ad300000-0000-4000-8000-000000000001', viewer='ad300000-0000-4000-8000-000000000002';
  const admin='ad300000-0000-4000-8000-000000000003', post='ad300000-0000-4000-8000-000000000004';
  const path=`${owner}/${post}/0.jpg`;
  try {
    await db.exec(`create role anon; create role authenticated;
      create schema auth; create schema storage;
      grant usage on schema auth,storage to anon,authenticated;
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      create table auth.users(id uuid primary key);
      insert into auth.users values('${owner}'),('${viewer}'),('${admin}');
      create function public.is_admin() returns boolean language sql stable as $$select auth.uid()='${admin}'::uuid$$;
      create table public.profiles(id uuid primary key,display_name text,avatar_url text,is_public boolean);
      create table public.community_posts(id uuid primary key default gen_random_uuid(),user_id uuid references auth.users(id) on delete cascade,
        content text not null check(length(btrim(content)) between 1 and 2000),achievement_tag text,created_at timestamptz default now(),topic text);
      alter table public.community_posts enable row level security;
      grant insert(user_id,content,achievement_tag,topic),delete on public.community_posts to authenticated;
      create policy "Community posts are public" on public.community_posts for select using(true);
      create policy own_insert on public.community_posts for insert to authenticated with check(user_id=auth.uid());
      create policy own_delete on public.community_posts for delete to authenticated using(user_id=auth.uid());
      create table public.community_post_likes(post_id uuid,user_id uuid);
      create table public.community_comments(post_id uuid);
      create table public.community_blocks(blocker_id uuid,blocked_id uuid);
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(bucket_id text references storage.buckets(id),name text,primary key(bucket_id,name));
      alter table storage.objects enable row level security;
      grant select,insert,delete on storage.objects to anon,authenticated;
    `);
    await db.exec(await Deno.readTextFile(new URL('../migrations/20261030000100_community_photo_feed.sql',import.meta.url)));
    const asUser=async(id:string,role='authenticated')=>{
      await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);
      await db.exec(`set role ${role}`);
    };
    const reserve=()=>db.query('select public.prepare_community_photos($1,$2)',[post,[path]]);
    await asUser('', 'anon'); await assert.rejects(reserve(),/permission denied|Entre/);
    await asUser(owner);
    await assert.rejects(db.query('select public.prepare_community_photos($1,$2)',[post,[`${viewer}/${post}/0.jpg`]]),/quatro/);
    await reserve();
    await assert.rejects(db.query('insert into public.community_posts(id,user_id,content,image_paths) values($1,$2,$3,$4)',[post,owner,'Relato',[path]]),/Envie todas/);
    await asUser(viewer);
    await assert.rejects(db.query("insert into storage.objects values('community-photos',$1)",[path]),/row-level security/);
    await asUser(owner);
    await db.query("insert into storage.objects values('community-photos',$1)",[path]);
    await db.query('insert into public.community_posts(id,user_id,content,image_paths) values($1,$2,$3,$4)',[post,owner,'Relato com foto',[path]]);
    assert.equal((await db.query('select * from public.community_photo_cleanup')).rows.length,0);
    await db.query("delete from storage.objects where bucket_id='community-photos' and name=$1",[path]);
    assert.equal((await db.query('select * from storage.objects')).rows.length,1);
    await asUser(viewer);
    assert.equal((await db.query('select * from public.community_posts')).rows.length,0);
    assert.equal((await db.query('select * from public.community_feed')).rows.length,1);
    assert.equal((await db.query('select * from storage.objects')).rows.length,1);
    for(const pair of [[owner,viewer],[viewer,owner]]) {
      await db.exec('reset role'); await db.query('insert into public.community_blocks values($1,$2)',pair);
      await asUser(viewer);
      assert.equal((await db.query('select * from public.community_feed')).rows.length,0);
      assert.equal((await db.query('select * from storage.objects')).rows.length,0);
      await db.exec('reset role'); await db.exec('delete from public.community_blocks');
    }
    await asUser('', 'anon');
    assert.equal((await db.query('select * from public.community_feed')).rows.length,1);
    assert.equal((await db.query('select * from storage.objects')).rows.length,1);
    await asUser(owner);
    await db.query('delete from public.community_posts where id=$1',[post]);
    assert.equal((await db.query('select * from public.community_photo_cleanup')).rows.length,1);
    await db.query('select public.ack_community_photo_cleanup($1)',[post]);
    assert.equal((await db.query('select * from public.community_photo_cleanup')).rows.length,1);
    await asUser(viewer);
    assert.equal((await db.query('select * from storage.objects')).rows.length,0);
    assert.equal((await db.query('select * from public.community_photo_cleanup')).rows.length,0);
    await asUser(admin);
    assert.equal((await db.query('select * from public.community_photo_cleanup')).rows.length,1);
    await db.query("delete from storage.objects where bucket_id='community-photos' and name=$1",[path]);
    await db.query('select public.ack_community_photo_cleanup($1)',[post]);
    assert.equal((await db.query('select * from public.community_photo_cleanup')).rows.length,0);
    await asUser(owner); await reserve();
    assert.equal((await db.query('select * from public.pending_community_photo_cleanup()')).rows.length,0);
    await db.query("insert into storage.objects values('community-photos',$1)",[path]);
    await db.query('select public.ack_community_photo_cleanup($1)',[post]);
    assert.equal((await db.query('select * from public.community_photo_cleanup')).rows.length,1);
    await db.exec('reset role');
    await asUser(owner);
    await db.query('insert into public.community_posts(id,user_id,content,image_paths) values($1,$2,$3,$4)',[post,owner,'Último relato',[path]]);
    await db.exec('reset role');
    await db.query('delete from auth.users where id=$1',[owner]);
    await asUser(admin);
    assert.equal((await db.query('select * from public.pending_community_photo_cleanup()')).rows.length,1);
    await db.query("delete from storage.objects where bucket_id='community-photos' and name=$1",[path]);
    await db.query('select public.ack_community_photo_cleanup($1)',[post]);
    assert.equal((await db.query('select * from public.community_photo_cleanup')).rows.length,0);
    await db.exec('reset role');
    const bucket=(await db.query<any>('select * from storage.buckets')).rows[0];
    assert.equal(bucket.public,false); assert.equal(Number(bucket.file_size_limit),2097152);
    assert.deepEqual(bucket.allowed_mime_types,['image/jpeg','image/png','image/webp']);
    assert.equal((await db.query<{valid:boolean}>('select public.valid_community_photo_paths($1,$2,$3) as valid',[owner,post,[path,path]])).rows[0].valid,false);
    await db.exec(`alter table auth.users add column raw_user_meta_data jsonb default '{}',add column email text,add column email_confirmed_at timestamptz;
      alter table storage.objects add column metadata jsonb;
      insert into auth.users(id,raw_user_meta_data) values('${owner}','{"display_name":"Current name","avatar_url":"https://example.invalid/current.gif"}');
      insert into public.profiles values('${owner}','Old name','https://example.invalid/old.jpg',true);`);
    await db.exec(await Deno.readTextFile(new URL('../migrations/20261030000200_community_media_identity.sql',import.meta.url)));
    await asUser(viewer);
    let identity=(await db.query<any>('select * from public.community_member_identities($1)',[[owner]])).rows[0];
    assert.equal(identity.name,'Current name'); assert.equal(identity.avatar_url,'https://example.invalid/current.gif');
    await db.exec('reset role');
    await db.query(`update auth.users set raw_user_meta_data='{"display_name":"New name","avatar_url":""}' where id=$1`,[owner]);
    await asUser(viewer);
    identity=(await db.query<any>('select * from public.community_member_identities($1)',[[owner]])).rows[0];
    assert.equal(identity.name,'New name'); assert.equal(identity.avatar_url,null);
    await db.exec('reset role'); await db.query('update public.profiles set is_public=false where id=$1',[owner]);
    await asUser(viewer);
    identity=(await db.query<any>('select * from public.community_member_identities($1)',[[owner]])).rows[0];
    assert.equal(identity.name,'Membro'); assert.equal(identity.avatar_url,null);
    await db.exec('reset role'); await db.query('insert into public.community_blocks values($1,$2)',[owner,viewer]);
    await asUser(viewer);
    assert.equal((await db.query('select * from public.community_member_identities($1)',[[owner]])).rows.length,0);
    await db.exec('reset role'); await db.exec('delete from public.community_blocks');
    await asUser(owner);
    assert.equal((await db.query<any>('select * from public.community_member_identities($1)',[[owner]])).rows[0].name,'New name');
    const gif=`${owner}/${post}/0.gif`, video=`${owner}/${post}/1.mp4`;
    await db.query('select public.prepare_community_photos($1,$2)',[post,[gif,video]]);
    await db.query(`insert into storage.objects(bucket_id,name,metadata) values('community-photos',$1,'{"size":100,"mimetype":"image/gif"}'),('community-photos',$2,'{"size":26214401,"mimetype":"video/mp4"}')`,[gif,video]);
    await assert.rejects(db.query('insert into public.community_posts(id,user_id,content,image_paths) values($1,$2,$3,$4)',[post,owner,'Media',[gif,video]]),/Formato ou tamanho/);
    await db.exec('reset role');
    await db.query(`update storage.objects set metadata='{"size":1000,"mimetype":"video/mp4"}' where name=$1`,[video]);
    await asUser(owner);
    await db.query('insert into public.community_posts(id,user_id,content,image_paths) values($1,$2,$3,$4)',[post,owner,'Media',[gif,video]]);
    assert.deepEqual((await db.query<any>('select image_paths from public.community_feed')).rows[0].image_paths,[gif,video]);
    await db.exec('reset role');
    const mediaBucket=(await db.query<any>('select * from storage.buckets')).rows[0];
    assert.equal(Number(mediaBucket.file_size_limit),26214400);
    assert.equal(mediaBucket.public,false);
    assert.ok(mediaBucket.allowed_mime_types.includes('image/gif') && mediaBucket.allowed_mime_types.includes('video/mp4'));
    await db.exec(await Deno.readTextFile(new URL('../migrations/20261030000300_community_html_art.sql',import.meta.url)));
    const htmlPost='ad300000-0000-4000-8000-000000000005', htmlPath=`${owner}/${htmlPost}/0.html`;
    await asUser(owner);
    await db.query('select public.prepare_community_photos($1,$2)',[htmlPost,[htmlPath]]);
    await db.query(`insert into storage.objects(bucket_id,name,metadata) values('community-photos',$1,'{"size":300,"mimetype":"text/html"}')`,[htmlPath]);
    await assert.rejects(db.query('insert into public.community_posts(id,user_id,content,image_paths) values($1,$2,$3,$4)',[htmlPost,owner,'HTML',[htmlPath]]),/Formato ou tamanho/);
    await db.exec('reset role');
    await db.query(`update storage.objects set metadata='{"size":300,"mimetype":"text/plain"}' where name=$1`,[htmlPath]);
    await asUser(owner);
    await db.query('insert into public.community_posts(id,user_id,content,image_paths) values($1,$2,$3,$4)',[htmlPost,owner,'HTML',[htmlPath]]);
    assert.equal((await db.query('select * from public.community_feed')).rows.length,2);
  } finally { await db.close(); }
});
