import { PGlite } from 'npm:@electric-sql/pglite@0.3';
import assert from 'node:assert/strict';

Deno.test('knowledge migration freezes original platinum and preserves privacy', async () => {
  const db = new PGlite();
  const owner = 'ad280000-0000-4000-8000-000000000001';
  const viewer = 'ad280000-0000-4000-8000-000000000002';
  try {
    const sql = await Deno.readTextFile(new URL('../migrations/20261028000200_knowledge_journey.sql', import.meta.url));
    const originalIds = [...sql.matchAll(/\('original','([^']+)'\)/g)].map(m => m[1]);
    assert.equal(originalIds.length, 57);
    await db.exec(`
      create role anon; create role authenticated; create schema auth;
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb);
      create table public.profiles(id uuid primary key,display_name text,avatar_url text,is_public boolean,share_progress boolean);
      create table public.challenge_catalog(id text primary key,title text not null default '',description text not null default '',total_days integer not null default 1,level text not null default 'iniciante',icon_key text not null default 'book');
      create table public.challenge_day_completions(user_id uuid,challenge_id text,completed_on date);
      create table public.community_blocks(blocker_id uuid,blocked_id uuid);
      create table public.community_follows(follower_id uuid,followed_id uuid);
      create table public.profile_achievement_awards(user_id uuid references auth.users(id),achievement_key text,granted_by uuid references auth.users(id),granted_at timestamptz default now(),primary key(user_id,achievement_key));
      alter table public.profile_achievement_awards enable row level security;
      grant select on public.profile_achievement_awards to authenticated;
      create policy own_awards on public.profile_achievement_awards for select to authenticated using(user_id=auth.uid());
      insert into auth.users values('${viewer}','viewer@example.invalid',now(),'{}');
      create table public.habit_reminder_settings(user_id uuid,time_zone text,selected_habit_keys text[],updated_at timestamptz);
      create table public.habit_completions(user_id uuid,completed_on date,habit_key text);
      insert into auth.users values('${owner}','member@example.invalid',now(),' {"profile_style":{"frame":"platinum"}}');
      insert into public.profiles values('${owner}','Membro',null,true,true);
      select set_config('request.jwt.claim.sub','${viewer}',false);
    `);
    for (const id of originalIds) {
      await db.query('insert into public.challenge_catalog(id) values($1)', [id]);
      await db.query('insert into public.challenge_day_completions values($1,$2,current_date)', [owner,id]);
    }
    await db.exec(sql);
    await db.exec(await Deno.readTextFile(new URL('../migrations/20261028000300_platinum_profile_effects.sql', import.meta.url)));
    await db.exec(await Deno.readTextFile(new URL('../migrations/20261028000400_legendary_platinum_covers.sql', import.meta.url)));
    await db.exec(await Deno.readTextFile(new URL('../migrations/20261028000500_legendary_platinum_frames.sql', import.meta.url)));
    await db.exec(await Deno.readTextFile(new URL('../migrations/20261028000600_supreme_crown.sql', import.meta.url)));
    await db.exec('set role authenticated');
    const read = async () => (await db.query<{profile: any}>('select public.community_member_profile($1) as profile',[owner])).rows[0].profile;
    const effects = async (frame: string,cover: string) => {
      await db.exec('reset role');
      await db.query(`update auth.users set raw_user_meta_data=jsonb_build_object('profile_style',jsonb_build_object('frame','platinum','frame_effect',$1::text,'cover_effect',$2::text)) where id=$3`,[frame,cover,owner]);
      await db.exec('set role authenticated');
      return read();
    };
    // Challenges and forged metadata cannot grant the hidden crown.
    assert.equal((await effects('supreme_crown','shimmer')).style.frame_effect,'orbit');
    await assert.rejects(db.query('select public.grant_profile_achievement($1,$2)',['member@example.invalid','supreme_crown']),/Somente/);
    await assert.rejects(db.query('insert into public.profile_achievement_awards(user_id,achievement_key,granted_by) values($1,$2,$3)',[owner,'supreme_crown',viewer]),/permission denied/);
    await db.exec('reset role');
    await db.query("update auth.users set email='amaralaragao31@gmail.com' where id=$1",[viewer]);
    await db.exec('set role authenticated');
    await db.query('select public.grant_profile_achievement($1,$2)',['member@example.invalid','supreme_crown']);
    assert.equal((await effects('supreme_crown','shimmer')).style.frame_effect,'supreme_crown');
    await db.exec('reset role');
    await db.query('update public.profiles set share_progress=false where id=$1',[owner]);
    await db.exec('set role authenticated');
    assert.equal((await read()).style.frame_effect,'supreme_crown');
    assert.equal((await read()).progress,undefined);
    await db.exec('reset role');
    await db.query('update public.profiles set share_progress=true where id=$1',[owner]);
    await db.query("delete from public.profile_achievement_awards where user_id=$1 and achievement_key='supreme_crown'",[owner]);
    await db.query("update auth.users set email='viewer@example.invalid' where id=$1",[viewer]);
    await db.exec('set role authenticated');
    await effects('orbit','shimmer');
    let result = await read();
    assert.equal(result.style.frame,'platinum');
    assert.equal(result.progress.completed,57);
    assert.equal(result.progress.total,62);
    assert.equal(result.progress.completed_ids.filter((id: string) => id.startsWith('knowledge_')).length,0);
    result=await effects('platinum_orbit','platinum_ascent');
    assert.equal(result.style.frame_effect,'platinum_orbit'); assert.equal(result.style.cover_effect,'platinum_ascent');
    result=await effects('platinum_orbit','platinum_throne');
    assert.equal(result.style.cover_effect,'platinum_throne');
    result=await effects('platinum_iron','platinum_ascent');
    assert.equal(result.style.frame_effect,'platinum_iron');
    result=await effects('knowledge_orbit','knowledge_constellation');
    assert.equal(result.style.frame_effect,'orbit'); assert.equal(result.style.cover_effect,'shimmer');
    result=await effects('journey_crown','journey_legacy');
    assert.equal(result.style.frame_effect,'orbit'); assert.equal(result.style.cover_effect,'shimmer');
    assert.equal((await db.query('select * from public.challenge_journey_members')).rows.length,62);
    await assert.rejects(db.exec("delete from public.challenge_journey_members where journey_id='original'"),/permission denied/);
    await db.exec('reset role');
    await db.exec(`delete from public.challenge_day_completions;
      insert into public.challenge_day_completions select '${owner}',c.id,current_date-n::integer from public.challenge_catalog c cross join lateral generate_series(1,c.total_days) n where c.id like 'knowledge_%';`);
    await db.exec('set role authenticated');
    result = await read();
    assert.equal(result.style.frame,'orange');
    assert.equal(result.progress.completed,5);
    result=await effects('platinum_iron','knowledge_constellation');
    assert.equal(result.style.frame_effect,'orbit');
    result=await effects('knowledge_orbit','platinum_throne');
    assert.equal(result.style.cover_effect,'shimmer');
    result=await effects('knowledge_orbit','knowledge_constellation');
    assert.equal(result.style.frame_effect,'knowledge_orbit'); assert.equal(result.style.cover_effect,'knowledge_constellation');
    result=await effects('platinum_orbit','platinum_ascent');
    assert.equal(result.style.frame_effect,'orbit'); assert.equal(result.style.cover_effect,'shimmer');
    result=await effects('journey_crown','journey_legacy');
    assert.equal(result.style.frame_effect,'orbit'); assert.equal(result.style.cover_effect,'shimmer');
    await db.exec(`reset role; insert into public.challenge_day_completions select '${owner}',id,current_date from public.challenge_catalog where id not like 'knowledge_%'; set role authenticated`);
    result=await effects('journey_crown','journey_legacy');
    assert.equal(result.style.frame_effect,'journey_crown'); assert.equal(result.style.cover_effect,'journey_legacy');
    await db.exec('reset role; update public.profiles set share_progress=false; set role authenticated');
    result = await read();
    assert.equal(result.progress,undefined);
    assert.deepEqual(result.style.featured,[]);
    await db.exec(`reset role; delete from public.challenge_day_completions;
      update auth.users set email='amaralaragao31@gmail.com',email_confirmed_at=now();
      update public.profiles set share_progress=true; set role authenticated`);
    result = await read();
    assert.equal(result.founder,true);
    assert.equal(result.progress.completed,62);
    assert.equal(result.progress.completed_ids.filter((id: string) => id.startsWith('knowledge_')).length,5);
    assert.equal(result.style.frame,'platinum');
    await db.exec('reset role; update public.profiles set is_public=false; set role authenticated');
    assert.equal(await read(),null);
  } finally { await db.close(); }
});
