import { PGlite } from 'npm:@electric-sql/pglite@0.3.16';
import assert from 'node:assert/strict';
Deno.test('private audio enforces verified duration, ownership, expiry and cleanup', async () => {
 const db=new PGlite();
 const a='cc070000-0000-4000-8000-000000000001',b='cc070000-0000-4000-8000-000000000002',c='cc070000-0000-4000-8000-000000000003';
 const message='cc070000-0000-4000-8000-000000000011',photo='cc070000-0000-4000-8000-000000000012';
 const as=async(id:string,role='authenticated')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec(`set role ${role}`);};
 try {
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create schema storage;
   grant usage on schema auth,storage to anon,authenticated;
   create schema vault;create schema cron;create schema net;
   create table vault.decrypted_secrets(name text,decrypted_secret text);
   create function cron.schedule(text,text,text) returns bigint language sql as $$select 1::bigint$$;
   create function net.http_post(url text,headers jsonb,body jsonb,timeout_milliseconds integer) returns bigint language sql as $$select 1::bigint$$;
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create table auth.users(id uuid primary key,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}');
   create table public.profiles(id uuid primary key,display_name text,avatar_url text,is_public boolean default true);
   create table public.member_handles(user_id uuid,handle text);
   create table public.community_blocks(blocker_id uuid,blocked_id uuid);
   create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
   create table storage.objects(bucket_id text,name text,unique(bucket_id,name));
   alter table storage.objects enable row level security;grant insert,select on storage.objects to authenticated;
   insert into auth.users(id,email_confirmed_at) values('${a}',now()),('${b}',now()),('${c}',now());
   insert into public.profiles(id,display_name) values('${a}','A'),('${b}','B'),('${c}','C');`);
  for(const migration of ['20261107000200_private_chat','20261107000300_chat_retention_delivery','20261107000400_private_chat_audio']) await db.exec(await Deno.readTextFile(new URL('../migrations/'+migration+'.sql',import.meta.url)));
  await as(a);
  const thread=(await db.query<any>('select public.chat_open($1) as id',[b])).rows[0].id;
  const path=(await db.query<any>("select public.chat_prepare_audio($1,$2,'webm') as path",[thread,message])).rows[0].path;
  assert.equal((await db.query<any>('select public.chat_image_upload_allowed($1) as ok',[path])).rows[0].ok,false);
  assert.equal((await db.query<any>("select public.chat_prepare_audio($1,$2,'webm') as path",[thread,message])).rows[0].path,path);
  await db.query("insert into storage.objects values('chat-audio',$1)",[path]);
  await assert.rejects(db.query('select public.chat_verify_audio($1,$2,1000,1000,$3)',[a,path,'webm']),/permission denied/);
  await assert.rejects(db.query('select public.chat_send_audio($1,$2,$3)',[thread,message,path]),/validado/);
  await as(c);
  assert.equal((await db.query("select * from storage.objects where bucket_id='chat-audio'")).rows.length,0);
  await assert.rejects(db.query("select public.chat_prepare_audio($1,$2,'webm')",[thread,photo]),/indispon/);
  await assert.rejects(db.query('select public.chat_send_audio($1,$2,$3)',[thread,message,path]),/indispon/);
  await db.exec('reset role');
  await assert.rejects(db.query("select public.chat_verify_audio($1,$2,120001,1000,'webm')",[a,path]),/dois minutos/);
  await assert.rejects(db.query("select public.chat_verify_audio($1,$2,120000,1048577,'webm')",[a,path]),/1 MB/);
  await db.query("select public.chat_verify_audio($1,$2,120000,500000,'webm')",[a,path]);
  await as(a);
  await db.query('select public.chat_send_audio($1,$2,$3)',[thread,message,path]);
  await db.query('select public.chat_send_audio($1,$2,$3)',[thread,message,path]);
  const messages=(await db.query<any>('select * from public.chat_messages')).rows;
  assert.equal(messages.length,1);assert.equal(messages[0].audio_duration_ms,120000);assert.equal(messages[0].audio_path,path);
  await as(b);
  assert.equal((await db.query<any>('select * from public.chat_inbox()')).rows[0].last_body,'🎤 Áudio');
  assert.equal((await db.query("select * from storage.objects where bucket_id='chat-audio'")).rows.length,1);
  await assert.rejects(db.query('select public.chat_delete_message($1)',[message]),/indispon/);
  await db.exec('reset role');await db.query('insert into public.community_blocks values($1,$2)',[b,a]);
  await as(a);assert.equal((await db.query('select * from public.chat_messages')).rows.length,0);
  assert.equal((await db.query("select * from storage.objects where bucket_id='chat-audio'")).rows.length,0);
  await db.exec('reset role');await db.exec("delete from public.community_blocks;update public.chat_messages set expires_at=now()-interval '1 second'");
  await as(b);assert.equal((await db.query('select * from public.chat_messages')).rows.length,0);
  await db.exec('reset role');await db.query('select public.chat_maintenance()');
  const queue=(await db.query<any>('select * from public.chat_claim_cleanup()')).rows;
  assert.equal(queue.length,1);assert.equal(queue[0].bucket,'chat-audio');assert.equal(queue[0].path,path);
  assert.equal((await db.query('select * from storage.objects')).rows.length,1);
  await db.query('select public.chat_ack_cleanup($1,$2)',[path,queue[0].claim_token]);
  assert.equal((await db.query('select * from public.chat_media_cleanup')).rows.length,0);
 } finally {await db.close();}
});
